/**
 * Query 构建（07-retrieval.md §3）：多轮里只补上"当前问题缺的主语"，其余一律不动。
 *
 * 为什么要拼上一轮：短追问（`那瓦数呢？` / `Und wie viel Watt?`）的主语只存在于上一轮，
 * 单独拿去检索，向量路会把它当成一句没有主题的话，召回全飘。
 *
 * 为什么不能每轮都拼：每轮都把历史接上去，query 会一轮一轮地漂移 —— 到第五轮它描述的是
 * 整段对话的"平均话题"，而不是用户此刻在问的东西，和当前问题越离越远。
 * 所以只在当前问题"过短或无实词"时拼：这时的当前问题自己活不了，必须借上一轮。
 *
 * 为什么不做模型改写：ADR-0003。改写要多一次模型调用（+约 1.5s 延迟），
 * 而且改写错一次就会污染整条链路 —— 检索、拒答、引用溯源全跟着错，且错在日志里看不出来。
 * 翻译同理：把德语追问翻成英语再检索，术语（`Wechselrichter`、`WT-ESS-5K`）会直接丢失。
 *
 * 因此本文件：无 import、无网络、无字典、无小写化、无去标点，纯同步纯函数。
 */

/** 当前问题长度 ≤ 该值即视为"短追问"（07 §3；单位是字符串长度，不是字符宽度）。 */
export const QUERY_STITCH_MAX_CHARS = 25;

/** 连续 3 个英文字母或汉字 = 一个实词。用来判断当前问题自己有没有主题词。 */
const CONTENT_WORD = /[a-zA-Z\u4e00-\u9fa5]{3,}/;

/**
 * 只在当前问题"过短或无实词"时拼接上一轮用户问题；否则原样返回当前问题。
 *
 * 空白问题返回 `""`（且绝不把空白拼到上一轮后面）—— 调用方据此直接返回空结果，
 * 不去打嵌入接口；拼出来的 `"上一轮\n"` 会检索到一个和用户此刻问题无关的结果。
 */
export function buildQuery(current: string, prevUser?: string): string {
  const cur = current.trim();
  if (cur === "") return "";

  const prev = prevUser?.trim() ?? "";
  if (prev === "") return cur;

  // "过短"和"无实词"是或关系：`OK?` 短且没有实词，`Und wie viel Watt?` 有实词但短，
  // 两种都得借上一轮；而一句自带主语的完整问句不需要，拼了反而稀释当前问题。
  if (cur.length <= QUERY_STITCH_MAX_CHARS || !CONTENT_WORD.test(cur)) {
    // 顺序固定：上一轮在前、当前在后，单个 \n 分隔（不是空行，避免被当成两段独立问题）
    return `${prev}\n${cur}`;
  }

  return cur;
}
